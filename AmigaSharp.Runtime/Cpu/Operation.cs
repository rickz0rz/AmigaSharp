namespace AmigaSharp.Runtime.Cpu;

/// <summary>
/// The 68000 operations.
/// </summary>
/// <remarks>
/// The immediate forms that target CCR or SR (for example ANDI to SR) use <see cref="Andi"/>, <see cref="Ori"/> and
/// <see cref="Eori"/> with a <see cref="AddressingMode.Ccr"/> or <see cref="AddressingMode.Sr"/> destination.
/// MOVE to CCR, MOVE to SR, MOVE from SR and MOVE USP use <see cref="Move"/> in the same way.
/// BRA is <see cref="Bcc"/> with <see cref="Condition.True"/>.
/// </remarks>
public enum Operation : byte
{
    Illegal,
    Abcd,
    Add,
    Adda,
    Addi,
    Addq,
    Addx,
    And,
    Andi,
    Asl,
    Asr,
    Bcc,
    Bchg,
    Bclr,
    Bset,
    Bsr,
    Btst,
    Chk,
    Clr,
    Cmp,
    Cmpa,
    Cmpi,
    Cmpm,
    Dbcc,
    Divs,
    Divu,
    Eor,
    Eori,
    Exg,
    Ext,
    Jmp,
    Jsr,
    Lea,
    LineA,
    LineF,
    Link,
    Lsl,
    Lsr,
    Move,
    Movea,
    Movem,
    Movep,
    Moveq,
    Muls,
    Mulu,
    Nbcd,
    Neg,
    Negx,
    Nop,
    Not,
    Or,
    Ori,
    Pea,
    Reset,
    Rol,
    Ror,
    Roxl,
    Roxr,
    Rte,
    Rtr,
    Rts,
    Sbcd,
    Scc,
    Stop,
    Sub,
    Suba,
    Subi,
    Subq,
    Subx,
    Swap,
    Tas,
    Trap,
    Trapv,
    Tst,
    Unlk,
}

/// <summary>The condition codes of Bcc, DBcc and Scc, in encoding order.</summary>
public enum Condition : byte
{
    True,
    False,
    Hi,
    Ls,
    Cc,
    Cs,
    Ne,
    Eq,
    Vc,
    Vs,
    Pl,
    Mi,
    Ge,
    Lt,
    Gt,
    Le,
}
